"""Vehicle images from the manifest's ``runtime.build`` section (task P1-T04, ADR-0004).

:func:`write_context` renders a build context from a manifest: a multi-stage ``Dockerfile`` on the
Fieldproof base image, the ``vehicle.repos`` file ``vcs import`` clones at the pinned commits, the
entry point that sources ROS 2 and the vehicle's install space, and the resolved manifest the image
carries at ``/opt/fieldproof/robot.yaml``. :func:`build_command` and :func:`run_command` compose the
``docker buildx build`` and ``docker run`` command lines the CLI runs (``fieldproof vehicle build``
and ``fieldproof vehicle run``), :func:`wait_command` the ``docker exec`` of the readiness probe
(``fieldproof vehicle wait``); the scenario orchestrator of P1-T05 drives the same image through
the Docker API.

The image is built in two stages so the runtime carries no compiler:

``build``
    the base image plus the ROS build tools; the sources land in ``/opt/vehicle_ws/src`` (local
    directories from the ``vehicle-source`` build context, repositories through ``vcs``); rosdep
    resolves their dependencies against one pinned commit of ros/rosdistro and
    ``fieldproof-apt-install`` fetches them in parallel from the base image's snapshots; ``colcon
    build --merge-install`` installs into ``/opt/vehicle``.
``runtime``
    the base image, the run-time dependencies rosdep listed for the packages built, the install
    space, the entry point, the manifest, the readiness probe (:mod:`fieldproof.vehicle_ready`,
    the image's ``HEALTHCHECK`` when the manifest has ``runtime.ready``), the labels; runs as the
    base image's non-root user with the manifest's entrypoint as the default command.
"""

from __future__ import annotations

import json
import shlex
import subprocess
from dataclasses import dataclass, field
from datetime import UTC, datetime
from importlib import resources
from pathlib import Path

import yaml

from fieldproof import __version__, vehicle_ready
from fieldproof.manifest import (
    DDS_PROFILE_IN_CONTAINER,
    DEFAULT_BASE_IMAGE,
    Build,
    RobotManifest,
    Runtime,
    load_manifest,
)
from fieldproof_bridge.manifest import ManifestError, read_manifest_data

SOURCE_CONTEXT = "vehicle-source"
# The buildx builder of the Docker daemon itself, which sees locally built images.
DEFAULT_BUILDER = "default"
INSTALL_BASE = "/opt/vehicle"
WORKSPACE = "/opt/vehicle_ws"
MANIFEST_IN_IMAGE = "/opt/fieldproof/robot.yaml"
EXEC_DEPS = ".fieldproof-exec-deps.txt"
ENTRYPOINT_IN_IMAGE = "/usr/local/bin/fieldproof-vehicle-entrypoint"
READY_IN_IMAGE = "/usr/local/bin/fieldproof-vehicle-ready"
READY_SOURCE = "ready.py"
# The HEALTHCHECK: the probe with a short wait, so each check reports promptly; Docker reports
# `starting` during the start period, `unhealthy` after `retries` failures and `healthy` as soon
# as one check passes. The manifest's ready.timeout_s is the budget of `vehicle wait`, not of a
# single check.
HEALTHCHECK = "--interval=15s --timeout=30s --start-period=60s --retries=3"
HEALTHCHECK_PROBE_TIMEOUT_S = 10
BUILD_TOOLS = (
    "build-essential",
    "cmake",
    "git",
    "python3-colcon-common-extensions",
    "python3-rosdep",
    "python3-vcstool",
)
REPO_URL = "https://github.com/Dimitrios-Kafetzis/Fieldproof"
# rosdep prints `  sudo -H apt-get install <pkg>` per package (no sudo when run as root).
APT_LINE = r"s/^ *\(sudo -H \)\{0,1\}apt-get install \(-y \)\{0,1\}//p"
ROSDISTRO_RAW = "https://raw.githubusercontent.com/ros/rosdistro"
# printf format of rosdep's source list; both %s take the pinned commit.
ROSDEP_SOURCES = (
    f"yaml {ROSDISTRO_RAW}/%s/rosdep/base.yaml\\nyaml {ROSDISTRO_RAW}/%s/rosdep/python.yaml\\n"
)

ENTRYPOINT = """\
#!/usr/bin/env bash
# Entry point of a Fieldproof vehicle image (generated by fieldproof vehicle dockerfile): source
# ROS 2 and the vehicle's install space, then run the command (the manifest's entrypoint by
# default). The setup scripts are not written for `set -u`.
set -eo pipefail
# shellcheck disable=SC1090,SC1091
source "/opt/ros/${ROS_DISTRO:-jazzy}/setup.bash"
# shellcheck disable=SC1091
source "%(install)s/setup.bash"
set -u
exec "$@"
"""


class VehicleError(ValueError):
    """The image cannot be generated, built or run as asked."""


def runtime_of(manifest: RobotManifest) -> Runtime:
    """The manifest's runtime section, or an error naming the manifest."""
    if manifest.runtime is None:
        raise VehicleError(f"{manifest.name}: the manifest has no runtime section")
    return manifest.runtime


def build_of(manifest: RobotManifest) -> Build:
    """The manifest's build section (a T1 image built from sources), or an error."""
    runtime = runtime_of(manifest)
    if runtime.build is None:
        raise VehicleError(
            f"{manifest.name}: runtime.build is absent, the image {runtime.image} is prebuilt"
        )
    if runtime.tier != "T1":
        raise VehicleError(
            f"{manifest.name}: tier {runtime.tier} images arrive with Phase 6 (ADR-0007)"
        )
    return runtime.build


def source_name(index: int, source: str) -> str:
    """Directory under ``src/`` a local source directory is copied to."""
    name = Path(source).name
    return name if name not in ("", ".") else f"vehicle{index}"


def manifest_origin(manifest: RobotManifest) -> str:
    """How the generated files name their manifest (relative to the working directory if below)."""
    if manifest.path is None:
        return "the manifest"
    try:
        return str(manifest.path.relative_to(Path.cwd()))
    except ValueError:
        return str(manifest.path)


def base_image_of(manifest: RobotManifest, base_image: str | None = None) -> str:
    """The base image of the manifest's build: its own, else `base_image`, else the default."""
    build = build_of(manifest)
    return build.base or base_image or DEFAULT_BASE_IMAGE


def render_dockerfile(
    manifest: RobotManifest, manifest_label: str | None = None, *, base_image: str | None = None
) -> str:
    """The multi-stage Dockerfile of the manifest's ``runtime.build``.

    `base_image` is the workspace's base image, the Dockerfile's default when the manifest
    names none (`docker buildx build --build-arg BASE_IMAGE=...` overrides either).
    """
    runtime = runtime_of(manifest)
    build = build_of(manifest)
    origin = manifest_label or manifest_origin(manifest)
    skip = f' --skip-keys "{" ".join(build.rosdep_skip_keys)}"' if build.rosdep_skip_keys else ""
    rosdep = (
        f"rosdep install --simulate --reinstall --from-paths src --ignore-src "
        f'--rosdistro "${{ROS_DISTRO}}"{skip}'
    )
    colcon_args = "".join(f" {shlex.quote(a)}" for a in build.colcon_args)
    apt_extras = " \\\n    && fieldproof-apt-install " + " ".join(build.apt) if build.apt else ""
    lines = [
        f"# Vehicle image of {manifest.name}, generated by `fieldproof vehicle dockerfile` from",
        f"# {origin}; regenerate, do not edit.",
        "#",
        "# Stage `build`: the base image plus the ROS build tools; the vehicle's sources (local",
        f"# directories from the `{SOURCE_CONTEXT}` build context, repositories at pinned",
        f"# commits through vcs) land in {WORKSPACE}/src, rosdep resolves their dependencies",
        f"# against one pinned commit of ros/rosdistro, colcon builds them into {INSTALL_BASE}",
        "# (merge-install). Stage `runtime`: the base image, the run-time dependencies rosdep",
        "# resolved, the install space, the entry point and the manifest, as the base image's",
        "# non-root user.",
        f"ARG BASE_IMAGE={base_image_of(manifest, base_image)}",
        "# hadolint ignore=DL3006",
        "FROM ${BASE_IMAGE} AS build",
        f"ARG ROSDISTRO_COMMIT={build.rosdistro_commit}",
        "# This stage only builds; the runtime stage below switches back to the non-root user.",
        "# hadolint ignore=DL3002",
        "USER root",
        'SHELL ["/bin/bash", "-o", "pipefail", "-c"]',
        "",
        "# Build tools from the snapshots the base image is pinned to (DL3008 and DL3009 as in",
        "# the base image: versions come from the snapshots, whose lists stay in the image).",
        "# hadolint ignore=DL3008,DL3009",
        "RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\",
        "    fieldproof-apt-install " + " ".join(BUILD_TOOLS),
        "",
        "# rosdep against one commit of ros/rosdistro, so the same keys resolve to the same",
        "# packages on every build (`rosdep init` would point at master).",
        "RUN mkdir -p /etc/ros/rosdep/sources.list.d \\",
        f"    && printf '{ROSDEP_SOURCES}' \\",
        '        "${ROSDISTRO_COMMIT}" "${ROSDISTRO_COMMIT}" '
        "> /etc/ros/rosdep/sources.list.d/20-default.list \\",
        f'    && ROSDISTRO_INDEX_URL="{ROSDISTRO_RAW}/${{ROSDISTRO_COMMIT}}/index-v4.yaml" \\',
        '        rosdep update --rosdistro "${ROS_DISTRO}"',
        "",
        f"WORKDIR {WORKSPACE}",
    ]
    if build.repos:
        lines += [
            "# The vehicle's repositories at the commits pinned in the manifest.",
            "COPY vehicle.repos ./",
            "RUN vcs import --input vehicle.repos src",
        ]
    for index, source in enumerate(build.sources):
        src = source.rstrip("/") or "."
        lines += [
            f"# Local sources `{src}` of the manifest's directory (`{SOURCE_CONTEXT}` context).",
            "# hadolint ignore=DL3022",
            f"COPY --from={SOURCE_CONTEXT} {src}/ src/{source_name(index, src)}/",
        ]
    lines += [
        "",
        "# Dependencies: rosdep lists the apt packages of every package in src/ (the run-time",
        "# ones are kept for the runtime stage) and fieldproof-apt-install fetches them in",
        "# parallel. A key that resolves to another installer (pip) fails the build: vendor it or",
        "# skip it.",
        "# hadolint ignore=DL3008,DL3009",
        "RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\",
        f"    {rosdep} > /tmp/deps.txt \\",
        f"    && {rosdep} --dependency-types exec > /tmp/exec-deps.txt \\",
        "    && if grep -E '^#\\[' /tmp/deps.txt | grep -qv '^#\\[apt\\]'; then \\",
        "        echo 'dependencies need an installer other than apt:' >&2; \\",
        "        grep -E '^#\\[' /tmp/deps.txt >&2; exit 1; fi \\",
        f"    && sed -n '{APT_LINE}' /tmp/deps.txt | sort -u > /tmp/apt.txt \\",
        f"    && sed -n '{APT_LINE}' /tmp/exec-deps.txt | sort -u > /tmp/{EXEC_DEPS} \\",
        "    && if [ -s /tmp/apt.txt ]; then xargs -a /tmp/apt.txt fieldproof-apt-install; fi",
        "",
        "# Build and install into one install space; the run-time dependency list goes with it.",
        'RUN source "/opt/ros/${ROS_DISTRO}/setup.bash" \\',
        f"    && colcon build --merge-install --install-base {INSTALL_BASE} \\",
        "        --event-handlers console_cohesion+ desktop_notification- status- \\",
        f"        --cmake-args -DCMAKE_BUILD_TYPE=Release{colcon_args} \\",
        f"    && mv /tmp/{EXEC_DEPS} {INSTALL_BASE}/{EXEC_DEPS}",
        "",
        "# hadolint ignore=DL3006",
        "FROM ${BASE_IMAGE} AS runtime",
        "ARG FIELDPROOF_USER=fieldproof",
        "USER root",
        'SHELL ["/bin/bash", "-o", "pipefail", "-c"]',
        "",
        f"COPY --from=build {INSTALL_BASE} {INSTALL_BASE}",
        "# Run-time dependencies of the packages built, from the same snapshots as the base.",
        "# hadolint ignore=DL3008,DL3009",
        "RUN --mount=type=cache,target=/var/cache/apt,sharing=locked \\",
        f"    if [ -s {INSTALL_BASE}/{EXEC_DEPS} ]; then "
        f"xargs -a {INSTALL_BASE}/{EXEC_DEPS} fieldproof-apt-install; fi" + apt_extras,
        "",
        f"COPY --chmod=755 entrypoint.sh {ENTRYPOINT_IN_IMAGE}",
        "# The directory first: --chmod would give an implicitly created parent the file mode.",
        f"RUN install -d -m 755 {Path(MANIFEST_IN_IMAGE).parent}",
        f"COPY --chmod=644 robot.yaml {MANIFEST_IN_IMAGE}",
        "# The readiness probe (fieldproof.vehicle_ready, copied unchanged): `fieldproof vehicle",
        "# wait` runs it through docker exec against the manifest's runtime.ready conditions.",
        f"COPY --chmod=755 {READY_SOURCE} {READY_IN_IMAGE}",
    ]
    if runtime.ready is not None:
        lines += [
            "# The same probe as the image's health check, so `docker inspect` and compose's",
            "# `--wait` see the stack's readiness; the ROS environment comes from the entry point.",
            f"HEALTHCHECK {HEALTHCHECK} \\",
            f'    CMD ["{ENTRYPOINT_IN_IMAGE}", "{READY_IN_IMAGE}", '
            f'"--timeout", "{HEALTHCHECK_PROBE_TIMEOUT_S}"]',
        ]
    env = {
        "FIELDPROOF_VEHICLE": manifest.name,
        "FIELDPROOF_MANIFEST": MANIFEST_IN_IMAGE,
        **runtime.env,
    }
    lines += [
        "ENV " + " \\\n    ".join(f"{k}={shlex.quote(v)}" for k, v in env.items()),
        "",
        "USER ${FIELDPROOF_USER}",
        "WORKDIR /home/${FIELDPROOF_USER}",
        f'ENTRYPOINT ["/usr/bin/tini", "--", "{ENTRYPOINT_IN_IMAGE}"]',
        "CMD " + json.dumps(runtime.entrypoint.argv()),
        "",
        "# OCI annotations; these ARGs sit last so a new revision or date invalidates no layer",
        "# (BASE_IMAGE and ROSDISTRO_COMMIT are redeclared: ARGs do not cross a FROM).",
        "ARG BASE_IMAGE",
        f"ARG ROSDISTRO_COMMIT={build.rosdistro_commit}",
        "ARG GIT_SHA=unknown",
        "ARG BUILD_DATE=1970-01-01T00:00:00Z",
        "ARG VERSION=0.0.0",
        f'LABEL org.opencontainers.image.title="fieldproof-vehicle-{manifest.name}" \\',
        f'      org.opencontainers.image.description="{manifest.metadata.description}" \\',
        f'      org.opencontainers.image.source="{REPO_URL}" \\',
        '      org.opencontainers.image.licenses="Apache-2.0" \\',
        '      org.opencontainers.image.vendor="Fieldproof" \\',
        '      org.opencontainers.image.revision="${GIT_SHA}" \\',
        '      org.opencontainers.image.created="${BUILD_DATE}" \\',
        '      org.opencontainers.image.version="${VERSION}" \\',
        '      org.opencontainers.image.base.name="${BASE_IMAGE}" \\',
        f'      io.fieldproof.vehicle="{manifest.name}" \\',
        f'      io.fieldproof.tier="{runtime.tier}" \\',
        f'      io.fieldproof.manifest-api="{manifest.api_version}" \\',
        '      io.fieldproof.rosdistro-commit="${ROSDISTRO_COMMIT}"',
    ]
    return "\n".join(lines) + "\n"


def render_repos(manifest: RobotManifest) -> str | None:
    """The ``vcs import`` file of ``runtime.build.repos`` (``None`` without repositories)."""
    repos = build_of(manifest).repos
    if not repos:
        return None
    data = {
        "repositories": {
            r.name: {"type": r.type, "url": r.url, "version": r.version} for r in repos
        }
    }
    header = f"# Generated by fieldproof vehicle dockerfile from {manifest.name}; pinned commits.\n"
    return header + str(yaml.safe_dump(data, sort_keys=False))


def resolved_manifest_text(manifest: RobotManifest) -> str:
    """The merged manifest document (``extends`` resolved) the image carries."""
    if manifest.path is None:
        raise VehicleError("the manifest must be loaded from a file to be copied into the image")
    data = read_manifest_data(manifest.path, robots=manifest.robots)
    header = (
        f"# Resolved vehicle manifest of {manifest.name}, written by fieldproof vehicle\n"
        f"# dockerfile from {manifest_origin(manifest)} (extends resolved; description paths\n"
        "# are the source checkout's).\n"
    )
    return header + str(yaml.safe_dump(data, sort_keys=False, width=100))


def ready_probe_source() -> str:
    """The readiness probe script the image carries (the engine module, unchanged)."""
    return (
        resources.files(vehicle_ready.__package__ or "fieldproof")
        .joinpath(Path(vehicle_ready.__file__).name)
        .read_text()
    )


def check_sources(manifest: RobotManifest) -> None:
    """Every local source directory and parameter file of the manifest exists."""
    runtime = runtime_of(manifest)
    base = manifest.directory
    for source in runtime.build.sources if runtime.build else []:
        if not (base / source).is_dir():
            raise VehicleError(
                f"{manifest.path}: runtime.build.sources: {source!r} is not a directory"
            )
    for params in runtime.params:
        if not (base / params).is_file():
            raise VehicleError(f"{manifest.path}: runtime.params: {params!r} is not a file")
    if runtime.dds_profile is not None and not (base / runtime.dds_profile).is_file():
        raise VehicleError(
            f"{manifest.path}: runtime.dds_profile: {runtime.dds_profile!r} is not a file"
        )


@dataclass
class Context:
    """A written build context."""

    directory: Path
    files: list[Path] = field(default_factory=list)

    @property
    def dockerfile(self) -> Path:
        """The Dockerfile in the context."""
        return self.directory / "Dockerfile"


def write_context(
    manifest: RobotManifest, out_dir: Path | str, *, base_image: str | None = None
) -> Context:
    """Write the build context of ``manifest`` into ``out_dir`` and return what was written.

    `base_image` is the workspace's base image, the Dockerfile's default when the manifest
    names none.
    """
    check_sources(manifest)
    directory = Path(out_dir)
    dockerfile = render_dockerfile(manifest, base_image=base_image)
    directory.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    files: dict[str, str] = {
        "Dockerfile": dockerfile,
        "entrypoint.sh": ENTRYPOINT % {"install": INSTALL_BASE},
        "robot.yaml": resolved_manifest_text(manifest),
        READY_SOURCE: ready_probe_source(),
    }
    repos = render_repos(manifest)
    if repos is not None:
        files["vehicle.repos"] = repos
    for name, text in files.items():
        path = directory / name
        path.write_text(text)
        written.append(path)
    return Context(directory, written)


def default_context_dir(manifest: RobotManifest) -> Path:
    """``./<name>_image`` in the current directory, like the bridge's bundles."""
    return Path.cwd() / f"{manifest.name}_image"


def git_revision(directory: Path) -> str:
    """The checkout's commit for the ``revision`` label, or ``unknown``."""
    try:
        completed = subprocess.run(  # noqa: S603  (fixed argument list)
            ["git", "-C", str(directory), "rev-parse", "HEAD"],  # noqa: S607
            capture_output=True,
            text=True,
            check=True,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return "unknown"
    return completed.stdout.strip() or "unknown"


def build_command(
    manifest: RobotManifest,
    context: Context,
    *,
    tag: str | None = None,
    base_image: str | None = None,
    no_cache: bool = False,
    progress: str | None = None,
    builder: str | None = DEFAULT_BUILDER,
    extra_args: tuple[str, ...] = (),
) -> list[str]:
    """The ``docker buildx build`` command line for a written context.

    The daemon's own builder (``default``) is selected unless ``builder`` says otherwise: the
    base image is usually a local build (``make images``), which a ``docker-container`` builder,
    such as the one GitHub's setup-buildx-action makes current, cannot see.
    """
    runtime = runtime_of(manifest)
    build = build_of(manifest)
    command = ["docker", "buildx", "build"]
    if builder:
        command += ["--builder", builder]
    command += [
        "--load",
        "--file",
        str(context.dockerfile),
        "--tag",
        tag or runtime.image,
        "--build-arg",
        f"GIT_SHA={git_revision(manifest.directory)}",
        "--build-arg",
        f"BUILD_DATE={datetime.now(UTC).strftime('%Y-%m-%dT%H:%M:%SZ')}",
        "--build-arg",
        f"VERSION={__version__}",
    ]
    if base_image:
        command += ["--build-arg", f"BASE_IMAGE={base_image}"]
    if build.sources:
        command += ["--build-context", f"{SOURCE_CONTEXT}={manifest.directory}"]
    if no_cache:
        command.append("--no-cache")
    if progress:
        command.append(f"--progress={progress}")
    command += [*extra_args, str(context.directory)]
    return command


def run_command(  # noqa: PLR0912
    manifest: RobotManifest,
    *,
    name: str | None = None,
    network: str | None = "fieldproof",
    domain_id: int | None = None,
    namespace: str = "",
    frame_prefix: str = "",
    detach: bool = False,
    remove: bool = True,
    image: str | None = None,
    env: dict[str, str] | None = None,
    extra_args: tuple[str, ...] = (),
    command: tuple[str, ...] = (),
) -> list[str]:
    """The ``docker run`` command line of the vehicle with its budget and environment.

    A `namespace` or `frame_prefix` goes into the environment (``FIELDPROOF_NAMESPACE``, which
    the readiness probe reads) and, when the manifest's launch names an argument for it, onto the
    launch command line in place of the image's default command (unless `command` is given). The
    manifest's DDS profile, if any, is mounted read-only and named to the RMW.
    """
    rt = runtime_of(manifest)
    argv = ["docker", "run"]
    if remove:
        argv.append("--rm")
    if detach:
        argv.append("--detach")
    argv += ["--name", name or manifest.name, "--hostname", name or manifest.name]
    if network:
        argv += ["--network", network]
    if domain_id is not None:
        argv += ["--env", f"ROS_DOMAIN_ID={domain_id}"]
    environment = dict(rt.env)
    if namespace:
        environment["FIELDPROOF_NAMESPACE"] = namespace
    if frame_prefix:
        environment["FIELDPROOF_FRAME_PREFIX"] = frame_prefix
    if rt.dds_profile is not None:
        profile = (manifest.directory / rt.dds_profile).resolve()
        argv += ["--volume", f"{profile}:{DDS_PROFILE_IN_CONTAINER}:ro"]
        environment.update(rt.dds_profile_env())
    for key, value in {**environment, **(env or {})}.items():
        argv += ["--env", f"{key}={value}"]
    if rt.resources is not None:
        if rt.resources.cpus is not None:
            argv += ["--cpus", f"{rt.resources.cpus:g}"]
        if rt.resources.cpuset is not None:
            argv += ["--cpuset-cpus", rt.resources.cpuset]
        if rt.resources.memory is not None:
            argv += ["--memory", rt.resources.memory]
        if rt.resources.pids is not None:
            argv += ["--pids-limit", str(rt.resources.pids)]
    if not command and (namespace or frame_prefix) and rt.entrypoint.launch is not None:
        command = tuple(rt.entrypoint.argv(namespace=namespace, frame_prefix=frame_prefix))
    argv += [*extra_args, image or rt.image, *command]
    return argv


def wait_command(
    manifest: RobotManifest,
    *,
    name: str | None = None,
    timeout_s: float | None = None,
    interval_s: float | None = None,
    quiet: bool = False,
) -> list[str]:
    """The ``docker exec`` of the readiness probe in the vehicle's running container.

    Without ``timeout_s`` the probe applies the manifest's ``ready.timeout_s`` (it reads the
    manifest the image carries); a manifest without ``ready`` is ready at once.
    """
    runtime_of(manifest)
    argv = ["docker", "exec", name or manifest.name, ENTRYPOINT_IN_IMAGE, READY_IN_IMAGE]
    if timeout_s is not None:
        argv += ["--timeout", f"{timeout_s:g}"]
    if interval_s is not None:
        argv += ["--interval", f"{interval_s:g}"]
    if quiet:
        argv.append("--quiet")
    return argv


def load_vehicle(path: Path | str, *, robots: Path | str | None = None) -> RobotManifest:
    """Load a manifest that has a runtime section (`robots` as for :func:`load_manifest`)."""
    manifest = load_manifest(path, robots=robots)
    if manifest.runtime is None:
        raise ManifestError(f"{manifest.path}: the manifest has no runtime section")
    return manifest
