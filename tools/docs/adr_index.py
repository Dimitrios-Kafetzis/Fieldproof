#!/usr/bin/env python3
"""Generate the index of Architecture Decision Records (task P0-T06).

Reads every ``docs/adr/NNNN-*.md`` except the ``0000`` template, takes the number and title from
the level-one heading (``# ADR-NNNN — Title``) and the status and date from the metadata list that
follows it, and writes the table to ``docs/adr/README.md``, which MkDocs serves as the section
index of the site and GitHub shows when browsing the directory.

Usage::

    tools/docs/adr_index.py --write [--adr-dir DIR]   rewrite the index when stale (default)
    tools/docs/adr_index.py --check [--adr-dir DIR]   exit 1 when stale or an ADR is malformed
    tools/docs/adr_index.py --print [--adr-dir DIR]   print the generated index to stdout

The pre-commit hook ``adr-index`` runs ``--write`` whenever an ADR changes, the MkDocs hook in
``mkdocs_hooks.py`` runs it before every build, and ``tests/docs/test_docs.sh`` runs ``--check``.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ADR_FILE = re.compile(r"^(?P<number>\d{4})-(?P<slug>[a-z0-9-]+)\.md$")
TITLE_LINE = re.compile(r"^# ADR-(?P<number>\d{4}) — (?P<title>\S.*)$")
FIELD_LINE = re.compile(r"^- \*\*(?P<name>[A-Za-z ]+):\*\* (?P<value>\S.*)$")
ADR_REFERENCE = re.compile(r"ADR-(\d{4})")
TEMPLATE_NUMBER = "0000"
INDEX_NAME = "README.md"

HEADER = """\
# Architecture Decision Records

<!-- Generated by tools/docs/adr_index.py from the ADR files in this directory. Do not edit by
     hand: the adr-index pre-commit hook and `make docs` regenerate it. -->

Every decision that shapes the stack is recorded here as an ADR
([04-engineering-standards.md](../plan/04-engineering-standards.md#documentation)). States run
Proposed → Accepted → Superseded or Deprecated; an accepted ADR changes only by a new ADR
superseding it.

| ADR | Title | Status | Date |
| --- | --- | --- | --- |
"""

FOOTER = """
New decisions start from [0000-adr-template.md](0000-adr-template.md) on a branch
`adr/<nnnn>-<slug>`, reviewed in their own pull request
([05-working-model.md](../plan/05-working-model.md#changing-the-plan)).
"""


class AdrError(Exception):
    """An ADR file does not follow the template closely enough to be indexed."""


@dataclass(frozen=True)
class Adr:
    """The indexed fields of one ADR."""

    number: str
    file_name: str
    title: str
    status: str
    date: str


def parse_adr(path: Path) -> Adr:
    """Extract number, title, status and date from one ADR file."""
    match = ADR_FILE.match(path.name)
    if match is None:
        raise AdrError(f"{path}: file name is not NNNN-slug.md")
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines:
        raise AdrError(f"{path}: empty file")
    title_match = TITLE_LINE.match(lines[0])
    if title_match is None:
        raise AdrError(f"{path}: first line must be '# ADR-NNNN — Title', got {lines[0]!r}")
    if title_match["number"] != match["number"]:
        raise AdrError(
            f"{path}: heading says ADR-{title_match['number']} but the file is numbered "
            f"{match['number']}"
        )
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.startswith("## "):
            break
        field = FIELD_LINE.match(line)
        if field is not None:
            fields[field["name"].lower()] = field["value"].strip()
    for required in ("status", "date"):
        if required not in fields:
            raise AdrError(
                f"{path}: no '- **{required.capitalize()}:**' line before the first section"
            )
    return Adr(
        number=match["number"],
        file_name=path.name,
        title=title_match["title"].strip(),
        status=fields["status"],
        date=fields["date"],
    )


def load_adrs(adr_dir: Path) -> list[Adr]:
    """Parse every ADR in the directory except the template, sorted by number."""
    adrs = [
        parse_adr(path)
        for path in sorted(adr_dir.glob("*.md"))
        if ADR_FILE.match(path.name) and not path.name.startswith(TEMPLATE_NUMBER)
    ]
    seen: dict[str, str] = {}
    for adr in adrs:
        if adr.number in seen:
            raise AdrError(
                f"{adr_dir}: ADR-{adr.number} exists twice ({seen[adr.number]}, {adr.file_name})"
            )
        seen[adr.number] = adr.file_name
    return adrs


def link_references(text: str, by_number: dict[str, Adr]) -> str:
    """Link ``ADR-NNNN`` mentions (as in ``Superseded by ADR-0012``) to the ADR when it exists."""

    def replace(match: re.Match[str]) -> str:
        target = by_number.get(match.group(1))
        return f"[{match.group(0)}]({target.file_name})" if target else match.group(0)

    return ADR_REFERENCE.sub(replace, text)


def render(adrs: list[Adr]) -> str:
    """Render the Markdown index for the given ADRs."""
    by_number = {adr.number: adr for adr in adrs}
    rows = [
        f"| [{adr.number}]({adr.file_name}) | {adr.title} "
        f"| {link_references(adr.status, by_number)} | {adr.date} |"
        for adr in adrs
    ]
    return HEADER + "\n".join(rows) + "\n" + FOOTER


def main(argv: list[str] | None = None) -> int:
    """Run the command line interface; return the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="rewrite README.md when stale (default)")
    mode.add_argument("--check", action="store_true", help="exit 1 when README.md is stale")
    mode.add_argument("--print", action="store_true", help="print the index instead of writing it")
    parser.add_argument(
        "--adr-dir",
        type=Path,
        default=Path(__file__).resolve().parents[2] / "docs" / "adr",
        help="directory holding the ADRs (default: docs/adr of this repository)",
    )
    args = parser.parse_args(argv)

    try:
        content = render(load_adrs(args.adr_dir))
    except (AdrError, OSError) as error:
        print(f"adr-index: {error}", file=sys.stderr)
        return 1

    index = args.adr_dir / INDEX_NAME
    if args.print:
        sys.stdout.write(content)
        return 0
    current = index.read_text(encoding="utf-8") if index.exists() else ""
    if current == content:
        print(f"adr-index: {index} is up to date")
        return 0
    if args.check:
        print(f"adr-index: {index} is stale; run tools/docs/adr_index.py --write", file=sys.stderr)
        sys.stderr.writelines(
            difflib.unified_diff(
                current.splitlines(keepends=True),
                content.splitlines(keepends=True),
                fromfile=str(index),
                tofile="generated",
            )
        )
        return 1
    index.write_text(content, encoding="utf-8")
    print(f"adr-index: {index} updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
