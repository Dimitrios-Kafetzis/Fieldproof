def write_bundle(bundle: Bundle, out_dir: Path) -> list[Path]:
    """Write ``bundle`` into ``out_dir`` (created if needed) and return the files written."""
    out_dir.mkdir(parents=True, exist_ok=True)
    header = GENERATED_HEADER.format(manifest=bundle.manifest or "a manifest")
    written: list[Path] = []
    for node in bundle.nodes:
        if node.config is not None:
            path = out_dir / node.config
            _dump(path, [entry.as_dict() for entry in node.entries], header)
            written.append(path)
    params = {
        bundle.fully_qualified(node.name): {"ros__parameters": dict(node.params)}
        for node in bundle.nodes
        if node.params
    }
    _dump(out_dir / "params.yaml", params, header)
    written.append(out_dir / "params.yaml")
    description = {
        "apiVersion": BUNDLE_API_VERSION,
        "kind": "BridgeBundle",
        "robot": bundle.robot,
        "manifest": str(bundle.manifest) if bundle.manifest else None,
        "namespace": bundle.namespace,
        "frame_prefix": bundle.frame_prefix,
        "clock": bundle.clock,
        "description": bundle.description,
        "tf": dict(bundle.tf),
        "nodes": [
            {
                "name": n.name,
                "kind": n.kind,
                **({"config": n.config} if n.config else {}),
                **({"topic": n.topic} if n.topic else {}),
                **({"sensor": n.sensor} if n.sensor else {}),
            }
            for n in bundle.nodes
        ],
        "internal_topics": bundle.internal_topics,
    }
    _dump(out_dir / "bridge.yaml", description, header)
    written.append(out_dir / "bridge.yaml")
    contract = {
        "apiVersion": BUNDLE_API_VERSION,
        "kind": "BridgeContract",
        "robot": bundle.robot,
        "namespace": bundle.namespace,
        "frame_prefix": bundle.frame_prefix,
        "topics": [topic.as_dict() for topic in bundle.topics],
    }
    _dump(out_dir / "contract.yaml", contract, header)
    written.append(out_dir / "contract.yaml")
    launch = out_dir / "bridge.launch.py"
    launch.write_text(LAUNCH_TEMPLATE.format(header=header, bundle=out_dir))
    written.append(launch)
    return written


def generate(
    manifest_path: Path | str,
    out_dir: Path | str,
    *,
    namespace: str = "",
    frame_prefix: str = "",
    clock: bool = True,
    robot_state_publisher: bool = True,
    without: tuple[str, ...] = (),
) -> list[Path]:
    """Load the manifest, plan the bundle and write it; return the files written."""
    manifest = Manifest.load(manifest_path)
    bundle = plan(
        manifest,
        namespace=namespace,
        frame_prefix=frame_prefix,
        clock=clock,
        robot_state_publisher=robot_state_publisher,
        without=without,
    )
    return write_bundle(bundle, Path(out_dir).resolve())


def default_out_dir(manifest_path: Path | str) -> Path:
    """``./<robot>_bridge`` next to the current directory, named after the manifest's robot."""
    return Path.cwd() / f"{Manifest.load(manifest_path).name}_bridge"


def build_parser() -> argparse.ArgumentParser:
    """The command line of ``ros2 run fieldproof_bridge bridge_gen``."""
    parser = argparse.ArgumentParser(
        prog="bridge_gen",
        description="Generate the ros_gz bridge bundle of a vehicle from its robot.yaml manifest.",
    )
    parser.add_argument("manifest", type=Path, help="the vehicle manifest (robot.yaml)")
    parser.add_argument(
        "-o", "--out", type=Path, default=None, help="output directory (default: ./<robot>_bridge)"
    )
    parser.add_argument("-n", "--namespace", default="", help="ROS namespace of the vehicle")
    parser.add_argument("--frame-prefix", default="", help="prefix of every frame (frame_prefix)")
    parser.add_argument("--no-clock", action="store_true", help="do not bridge /clock")
    parser.add_argument(
        "--no-robot-state-publisher",
        action="store_true",
        help="do not run robot_state_publisher from the manifest's description",
    )
    parser.add_argument(
        "--without",
        action="append",
        default=[],
        metavar="SENSOR",
        help="leave an optional sensor out (repeatable)",
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    """Console script entry point; returns the exit code."""
    args = build_parser().parse_args(argv)
    try:
        out = args.out if args.out is not None else default_out_dir(args.manifest)
        written = generate(
            args.manifest,
            out,
            namespace=args.namespace,
            frame_prefix=args.frame_prefix,
            clock=not args.no_clock,
            robot_state_publisher=not args.no_robot_state_publisher,
            without=tuple(args.without),
        )
    except (ManifestError, GeneratorError) as error:
        sys.stderr.write(f"bridge_gen: {error}\n")
        return 2
    for path in written:
        sys.stdout.write(f"{path}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
