"""Generate the bridge bundle of a vehicle from its manifest.

A bundle is a directory the bridge launch file (``launch/bridge.launch.py``) starts from::

    bridge.yaml                   what to start: bridge instances, adapters, robot_state_publisher
    params.yaml                   ROS parameters of those nodes (QoS overrides, adapter settings)
    ros_gz_bridge.yaml            parameter_bridge configuration (one entry per bridged topic)
    ros_gz_bridge_<frame>.yaml    one more instance per relabelled frame (override_frame_id)
    contract.yaml                 the ROS interface: topic, type, frame, rate and QoS of each topic
    bridge.launch.py              `ros2 launch <bundle>/bridge.launch.py` starts the bundle

The rules, applied to every interface of the manifest (:mod:`fieldproof_bridge.manifest`):

- Names are fully qualified with the vehicle namespace on both sides; a ROS topic written with a
  leading slash in the manifest stays global. The TF topics follow the drive's ``tf`` interface:
  relative (``tf``, the reference vehicles) puts ``/<namespace>/tf`` and ``/<namespace>/tf_static``
  under the namespace, one TF tree per vehicle (Nav2's multi-robot convention, task P2-T01);
  absolute (``/tf``) keeps one shared tree, where a ``frame_prefix`` tells the vehicles apart.
- A plain output goes through the main ``parameter_bridge`` instance with the declared QoS set
  through rclcpp's ``qos_overrides`` parameters.
- An output whose ROS frame differs from the frame Gazebo sets goes through one more
  ``parameter_bridge`` instance per frame, which relabels with ``override_frame_id`` (no copy in
  Python, so camera images stay in C++).
- An IMU gets the ``imu_adapter`` (covariance from the noise figures), a GNSS fix the
  ``navsat_adapter`` (frame, covariance, status), an interface with ``gz_rate`` the ``throttle``,
  every other output of an injectable type (a laser scan, an odometry, joint states: small
  messages at up to 100 Hz) the ``relay``; the bridge then publishes on a hidden topic
  (``<namespace>/_bridge/<topic>``) that the adapter reads, and the adapter publishes the
  contract topic with the declared QoS. Every adapter is a **fault injector** (task P2-T03): the
  timeline's sensor faults set its parameters. Images, camera info and point clouds stay on the
  C++ path through the bridge instances.
- The drive command goes through the ``command_relay``: the vehicle publishes the contract
  topic, the relay republishes on the hidden topic the bridge forwards to Gazebo, and the
  ``actuator.limit`` event caps the speeds in between.
- A ``power.battery`` section adds the ``battery`` node, which publishes the synthetic battery
  state the ``battery.drain`` event drains.
- ``/clock`` is bridged from the simulator unless disabled; ``robot_state_publisher`` runs from
  the manifest's xacro (same arguments as the spawn) unless disabled, which adds ``/tf_static``
  and ``robot_description`` to the contract.

Plain Python: the engine's ``fieldproof bridge gen`` and ``ros2 run fieldproof_bridge bridge_gen``
both call :func:`generate`.
"""

